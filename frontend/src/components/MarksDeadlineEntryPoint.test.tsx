import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import * as config from './MarkEntryPeriodConfig';
import * as assignment from './EvaluationTaskAssignment';
assert.equal(typeof config.MarksPeriodDeadlineControls,'function','Published period deadline controls must route to Periods & deadlines');
assert.equal(typeof assignment.MarksTaskDeadlineEntryPoint,'function','Task extra time must route to Periods & deadlines');
const base={value:'2026-10-20T12:00',onChange:()=>{},onManageTimeline:()=>{}};
const published=renderToStaticMarkup(<config.MarksPeriodDeadlineControls {...base} editable={false}/>);
assert.match(published,/type="datetime-local" disabled=""/);
assert.match(published,/Manage deadlines in Periods &amp; deadlines/);
const draft=renderToStaticMarkup(<config.MarksPeriodDeadlineControls {...base} editable/>);
assert.doesNotMatch(draft,/disabled=""|Manage deadlines in Periods &amp; deadlines/);
const central=renderToStaticMarkup(<assignment.MarksTaskDeadlineEntryPoint tasks={[]} onChanged={async()=>{}} onManageTimeline={()=>{}}/>);
assert.match(central,/Manage deadlines in Periods &amp; deadlines/);
assert.doesNotMatch(central,/Grant extra time|New deadline|Grant completion/);
let routed=0;
const element=assignment.MarksTaskDeadlineEntryPoint({tasks:[],onChanged:async()=>{},onManageTimeline:()=>{routed+=1;}});
const shortcut=React.Children.toArray(element.props.children).find((child:any)=>child.props?.onClick) as React.ReactElement<{onClick:()=>void}>;
assert.ok(shortcut,'Central shortcut exposes the supplied navigation action');
shortcut.props.onClick();
assert.equal(routed,1);
console.log('Published Marks deadlines and completion windows use the standalone Periods & deadlines entry point; draft dates stay editable');
