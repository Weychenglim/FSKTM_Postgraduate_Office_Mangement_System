import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as office from './SupervisorAppointmentManagement';
assert.ok('OfficeSupervisorRecordTable' in office, 'Office exposes compact loaded rows for records');
const rows:any[]=[{studentId:'M1',studentName:'Student One',programme:'Programme A',supervisor:'Dr One',status:'Pending',updatedDate:'10 Oct 2026',waitingDays:3,waitingOn:'PROGRAMME_COORDINATOR',semester:'S1',applicationId:7}];
const html=renderToStaticMarkup(React.createElement((office as any).OfficeSupervisorRecordTable,{records:rows,onOpen:()=>{},onDossier:()=>{}}));
assert.match(html, /Current stage/);
assert.match(html, /Waiting at this stage/);
assert.match(html, /3 calendar days/);
assert.match(html, /Awaiting Coordinator approval/);
assert.match(html, /View request/);
assert.match(html, /data-table/);
assert.doesNotMatch(html, /font-mono|Research abstract/);
assert.doesNotMatch(html, /�/);
assert.ok(html.indexOf('Student One') < html.indexOf('M1'), 'Student name leads the identity');
assert.ok('filterOfficeSupervisorRecords' in office);
const filter=(office as any).filterOfficeSupervisorRecords;
assert.equal(filter(rows,{search:'',programme:'All Programmes',semester:'S2',status:'All Records'}).length,0, 'Semester applies to loaded records');
assert.equal(filter(rows,{search:'M1',programme:'Programme A',semester:'S1',status:'Pending'}).length,1);
const sharedStudent = [rows[0], { ...rows[0], applicationId: 8, status: 'Cancelled' }];
const tableKeys = (records: any[]) => {
  const element = office.OfficeSupervisorRecordTable({ records, onOpen: () => {}, onDossier: () => {} }) as any;
  return element.props.children[1].props.children.map((row: any) => row.key);
};
const keys = tableKeys(sharedStudent);
assert.equal(new Set(keys).size, sharedStudent.length, 'Different applications for one student must have distinct row identities to prevent stale filter rows');
assert.equal(tableKeys([{ ...rows[0], status: 'Approved' }])[0], keys[0], 'A decision must not change the identity of the same application');
console.log('Office records use shared hierarchy styles, explicit actions and actual semester filtering');
