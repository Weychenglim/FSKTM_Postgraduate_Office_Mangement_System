import assert from 'node:assert/strict';
import {completeDecision, createDecisionSubmission, decisionFailure} from './decisionSubmission';

let saved=0, refreshed=0;
assert.deepEqual(await completeDecision(async()=>{saved++;},async()=>{refreshed++;}),{});
assert.equal(saved,1); assert.equal(refreshed,1);
const failure = new Error('Save unavailable');
await assert.rejects(completeDecision(async()=>{throw failure;},async()=>{refreshed++;}),error=>error===failure);
assert.equal(refreshed,1,'Never refresh or report success after a failed save');
assert.deepEqual(await completeDecision(async()=>{saved++;},async()=>{throw new Error('Reload unavailable');}),{refreshFailed:true});
assert.equal(saved,2,'Reload failure is a committed decision, not a reason to retry the save');
let release!:()=>void;
let operations=0;
const submission=createDecisionSubmission();
const pending=submission.run(async()=>{operations++;await new Promise<void>(resolve=>{release=resolve;});return 'saved';});
assert.equal(submission.isBusy(),true);
assert.deepEqual(await submission.run(async()=>{operations++;return 'duplicate';}),{started:false});
release();
assert.deepEqual(await pending,{started:true,value:'saved'});
assert.equal(operations,1); assert.equal(submission.isBusy(),false);
await assert.rejects(submission.run(async()=>{throw failure;}));
assert.equal(submission.isBusy(),false,'A failed save releases the duplicate-submit lock');
for(const status of [403,409]) assert.equal(decisionFailure({status,message:'Review latest state'}).blocked,true);
assert.equal(decisionFailure({status:500,message:'Server unavailable'}).blocked,false);
assert.equal(decisionFailure(new Error('Network unavailable')).message,'Network unavailable');
const conflicted=createDecisionSubmission();
await assert.rejects(conflicted.run(async()=>{throw {status:409,message:'Record changed'};}));
assert.equal(conflicted.isBlocked(),true);
assert.deepEqual(await conflicted.run(async()=>{throw new Error('Must not retry stale action');}),{started:false},'Closing/reopening a dialog does not release its stale-record block');
conflicted.clearBlock();
assert.deepEqual(await conflicted.run(async()=> 'reviewed latest record'),{started:true,value:'reviewed latest record'});
console.log('Decision save/reload separation, duplicate exclusion and conflict classification passed');
