import assert from 'node:assert/strict';
import { listenForReturnToFocus } from './returnToFocus';

const browser = new EventTarget();
const page = Object.assign(new EventTarget(), { visibilityState: 'visible' });
let reloads = 0;
let enabled = true;
const stop = listenForReturnToFocus(browser, page, () => { if (enabled) reloads += 1; });
browser.dispatchEvent(new Event('focus'));
assert.equal(reloads, 0, 'Initial focus does not duplicate the initial load');
browser.dispatchEvent(new Event('blur'));
page.visibilityState = 'hidden';
page.dispatchEvent(new Event('visibilitychange'));
browser.dispatchEvent(new Event('focus'));
assert.equal(reloads, 0, 'A hidden page never reloads');
page.visibilityState = 'visible';
page.dispatchEvent(new Event('visibilitychange'));
browser.dispatchEvent(new Event('focus'));
assert.equal(reloads, 1, 'Visibility and focus share one return load');
enabled = false;
browser.dispatchEvent(new Event('blur'));
browser.dispatchEvent(new Event('focus'));
assert.equal(reloads, 1, 'An active draft suppresses the return load');
enabled = true;
browser.dispatchEvent(new Event('blur'));
browser.dispatchEvent(new Event('focus'));
assert.equal(reloads, 2, 'A later return loads when the draft is closed');
stop();
browser.dispatchEvent(new Event('blur'));
browser.dispatchEvent(new Event('focus'));
assert.equal(reloads, 2, 'Unmounted pages no longer reload');
console.log('Return-to-focus loading preserves drafts and avoids duplicate loads');
